// 检索评估标注集(人工核心集)。chunk id = schema 驱动的 `${resource}::${path}`。
// 结构对齐方案 §2.3 的 EvalCase superset(检索/解释类字段;生成/修复类留到 Stage 4)。
// 设计:覆盖收敛后语料(26 资源,工作负载主导)+ 大量「易混淆硬负例」+ 少量「拒答用例」。
// 校验用 `npm run eval:check`。拒答用例 answerable=false / expectedChunkIds=[],不进 Recall/MRR。

export interface EvalCase {
  /** 稳定唯一 id(bad-case 回灌用 convertedEvalId 引用) */
  id: string;
  /** 任务类型:评估标准不同 */
  taskType: 'explain_field' | 'explain_error' | 'ask_free' | 'refusal' | 'crd';
  question: string;
  /** 可答用例:应被召回的正确 chunk id(s);拒答用例为空 */
  expectedChunkIds: string[];
  /** 目标资源(oracle/auto 软加权对齐);拒答用例可空 */
  resource?: string;
  /** false=拒答/不可答用例,不计入 Recall@k / MRR */
  answerable: boolean;
  /** 来源:人工 / schema 反向派生 / bad case 回灌 */
  source: 'human' | 'schema_generated' | 'bad_case';
  // superset 兼容(Stage 2 暂不填)
  apiVersion?: string;
  path?: string;
}

